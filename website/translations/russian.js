// in russian the word changes with the number: 1 программа, 2 программы, 5 программ
function russianPlural(n, one, few, many) {
    const lastDigit = n % 10;
    const lastTwo = n % 100;
    if (lastDigit === 1 && lastTwo !== 11) return one;
    if (lastDigit >= 2 && lastDigit <= 4 && (lastTwo < 12 || lastTwo > 14)) return few;
    return many;
}

function russianGrade(n) {
    if (n === 0) return 'подготовительный класс';
    return n + '-й класс';
}

